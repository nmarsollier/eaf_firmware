#include "freertos/semphr.h"

/* =========================================================================
 * Motion command queue.
 *
 * External callers send a MotionCommand to the queue. The motion task is
 * the sole consumer and the sole writer of the position counter.
 * ========================================================================= */

typedef struct {
    int64_t target_steps;   /* absolute target, or relative delta when `relative` */
    bool relative;          /* true → target_steps is a delta from current */
    /* Stop epoch captured at enqueue — a command whose epoch is stale
     * (a STOP landed after it was enqueued) is discarded at execution. */
    uint32_t generation;
} MotionCommand;

/* Queue handle — created by motors_queue_init(), shared across the module. */
extern QueueHandle_t motion_cmd_queue;

/* Binary semaphore used as an "idle token": taken by the motion task while a
 * command is in flight, given back when it settles (done or aborted). Created
 * available, so motors_stop() can take it — blocking until the task is idle —
 * then give it back, returning with the final counter. */
extern SemaphoreHandle_t motors_idle_sem;

/* Stop epoch — incremented on every stop so queued commands can be
 * invalidated. Monotonic uint32. */
extern volatile uint32_t motors_stop_generation;

/* Spinlock guarding the int64_t position counter and status. */
extern portMUX_TYPE motors_state_lock;

/* Send a MotionCommand to the back of the queue (FIFO). */
bool motors_queue_put(MotionCommand *cmd);

/* Atomically discard every command in the queue. */
void motors_queue_clear(void);

/* =========================================================================
 * Hardware layer.
 * ========================================================================= */

typedef enum {
    MOTOR_DIRECTION_NEGATIVE = 0,
    MOTOR_DIRECTION_POSITIVE = 1,
} MotorDirection;

esp_err_t motors_hw_init(void);

void motors_hw_set_direction(MotorDirection direction);

/* Drive the TMC2209 EN pin — LOW = enabled, HIGH = disabled. */
void motors_hw_set_enabled(bool enabled);

/* Re-apply the desired enable state after a TMC re-init (power recovery). */
void motors_enable_reapply(void);

/* =========================================================================
 * RMT step pulse generation (motors_rmt.c).
 *
 * STEP pulses are generated by the RMT peripheral (2 MHz, 0.5 µs/tick),
 * a single FIFO channel, no DMA. Each symbol is a HIGH pulse followed by
 * an idle LOW that spans the rest of the step period.
 * ========================================================================= */

#define RMT_RESOLUTION_HZ    2000000U   /* 0.5 µs per tick */
#define STEP_PULSE_TICKS     4U         /* 2 µs HIGH */
#define STEP_MIN_LOW_TICKS   4U         /* 2 µs LOW */
#define STEP_MIN_PERIOD_TICKS (STEP_PULSE_TICKS + STEP_MIN_LOW_TICKS)

/* Non-DMA RMT FIFO capacity in symbols (one step = one symbol at focuser
 * speeds). Batches are capped to this so a transmit never overflows the
 * channel memory. */
#define RMT_MEM_BLOCK_SYMBOLS 48U

esp_err_t motors_rmt_init(void);

/* Encode `count` uniform-period steps (one symbol per step). */
uint32_t motors_rmt_encode_steps(rmt_symbol_word_t *symbols,
                                 uint32_t max_symbols,
                                 uint32_t period_ticks,
                                 uint32_t count);

/* Transmit `count` symbols and block until the RMT peripheral finishes. */
esp_err_t motors_rmt_transmit(const rmt_symbol_word_t *symbols, uint32_t count);

/* =========================================================================
 * Module state.
 * ========================================================================= */

extern MotorsState motors_state;

/* Status transitions — the single owner of motors_state.status. Every command
 * source (move, stop, enable/disable, power, error) routes its status change
 * through these (motors_transition.c). */
MotorResultCode motors_transition_reserve(void);
void motors_transition_moving(void);
void motors_transition_settle(void);
void motors_transition_disable(void);
void motors_transition_enable(void);
void motors_transition_error(void);
void motors_transition_recover(bool enabled);

/* Hardware-fault latch — set by motors_init() failure paths. */
void motors_enter_hardware_fault(void);

/* Mark the current ERROR as a recoverable power fault so a later power-on
 * re-initialises the driver (motors_power.c). */
void motors_mark_power_fault(void);

/* =========================================================================
 * Task & queue lifecycle.
 * ========================================================================= */

esp_err_t motors_motion_task_init(void);

esp_err_t motors_queue_init(void);
